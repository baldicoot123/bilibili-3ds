	if (p->adec) avcodec_free_context(&p->adec);
	if (p->bsf) av_bsf_free(&p->bsf);
	if (p->swr) swr_free(&p->swr);
	if (p->vframe) av_frame_free(&p->vframe);
	if (p->aframe) av_frame_free(&p->aframe);
